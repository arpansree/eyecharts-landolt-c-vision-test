"""Run the EyeCharts Landolt C prototype or check a saved screenshot."""
import argparse
import json
import shutil
import subprocess
import sys
import time
from dataclasses import asdict
from pathlib import Path
from report import save_report, validate_session_id


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    # these are separate checks, so pick just one or leave them off for a full test
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--image", type=Path, help="Read a saved screenshot without starting a session.")
    mode.add_argument("--audio-file", type=Path, help="Check Whisper with an audio file.")
    mode.add_argument("--prepare", action="store_true", help="Download and load Whisper before a session.")
    mode.add_argument("--check", action="store_true", help="Test spoken output and read the live starting chart.")
    parser.add_argument("--monitor", type=int, default=1, help="MSS display number, starting at 1.")
    parser.add_argument("--microphone", type=int, help="PortAudio input device number.")
    parser.add_argument("--listen-seconds", type=float, default=8, help="Maximum seconds to listen for each row answer.")
    parser.add_argument("--start-at", default="20/200", choices=("20/200", "20/50"),
                        help="First scored row in each round. The chart still resets to 20/200.")
    parser.add_argument("--device", choices=("cpu", "cuda"), default="cpu")
    parser.add_argument("--model-dir", help="Optional location for the Whisper model cache.")
    parser.add_argument("--tesseract", default="tesseract", help="Tesseract executable or path.")
    parser.add_argument("--session-id", type=validate_session_id,
                        help="Use this kiosk session ID in the results filename. A unique ID is generated by default.")
    parser.add_argument("--timing", action="store_true", help="Show timing and retry counts after a completed test.")
    args = parser.parse_args()
    if not 2 <= args.listen_seconds <= 30:
        parser.error("--listen-seconds must be between 2 and 30.")
    try:
        run(args)
    except KeyboardInterrupt:
        print("\nSession canceled.", file=sys.stderr)
        return 130
    except (RuntimeError, OSError, subprocess.SubprocessError, ValueError) as error:
        print(f"EyeCharts prototype stopped. {error}", file=sys.stderr)
        return 1
    return 0


def run(args):
    # the audio checks don't need EyeCharts or screen recording
    if args.prepare or args.audio_file:
        from speech_input import SpeechInput

        if args.audio_file and not args.audio_file.is_file():
            raise FileNotFoundError(args.audio_file)
        speech = SpeechInput(args.device, args.microphone, args.model_dir, prepare=args.prepare)
        if args.audio_file:
            print(speech.transcribe(str(args.audio_file)))
        return

    from chart_reader import Chart, ChartError, read_acuity, read_directions

    if not shutil.which(args.tesseract):
        raise ChartError("Install Tesseract or pass --tesseract with its executable path.")
    if args.image:
        import numpy as np
        from PIL import Image

        with Image.open(args.image) as screenshot:
            image = np.asarray(screenshot.convert("L"))
        chart = Chart(read_acuity(image, args.tesseract), read_directions(image))
        print(json.dumps(asdict(chart)))
        return

    from desktop import EyeChartsDesktop
    from speech_input import SpeechInput
    from workflow import VisionTest

    desktop = EyeChartsDesktop(args.monitor)
    with desktop.session(controls=not args.check):
        if args.check:
            chart = VisionTest(desktop, None, args.tesseract, args.listen_seconds).starting_chart(reposition=False)
            print(json.dumps(asdict(chart)))
            desktop.say("The display check passed. The starting chart is readable.")
            return
        started = time.monotonic()
        speech = SpeechInput(args.device, args.microphone, args.model_dir)
        test = VisionTest(desktop, speech, args.tesseract, args.listen_seconds)
        try:
            # get the mic ready before the app asks the person to say anything
            with speech.microphone_session():
                # setup ends when the model and mic are both ready, before the welcome prompt
                setup_seconds = time.monotonic() - started
                test.run(start_at=args.start_at)
        except ChartError:
            desktop.say("The vision test could not continue.")
            raise
        # save the three round results so the kiosk can pick them up later
        path = save_report(test.session.results, getattr(args, "session_id", None))
        print(f"Results saved locally to {path}", flush=True)
        desktop.say("The vision test is complete.")
        elapsed = time.monotonic() - started
        print(f"Vision test elapsed time: {elapsed:.1f} seconds.", flush=True)
        if getattr(args, "timing", False):
            # show the timings in the terminal only. the results file still has just the three scores
            timing = test.timings
            # retries already fall into these buckets, so don't subtract them a second time
            other = elapsed - setup_seconds - timing["readiness"] - timing["row_recording"] - timing["row_decode_wait"]
            print(
                f"Setup: {setup_seconds:.1f}s\n"
                f"Readiness prompts and responses: {timing['readiness']:.1f}s ({timing['readiness_retries']} retries)\n"
                f"Row microphone time: {timing['row_recording']:.1f}s\n"
                f"Row wait after the mic closed: {timing['row_decode_wait']:.1f}s\n"
                f"Prompts, chart changes, and other work: {other:.1f}s\n"
                f"Row retries: {timing['row_retries']} ({timing['row_retry_seconds']:.1f}s included above)",
                flush=True,
            )


if __name__ == "__main__":
    sys.exit(main())
